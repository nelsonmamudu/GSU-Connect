#!/usr/bin/env bash
# WARNING (2026-11-21): This script fails bash syntax validation and is unverified.
# It does NOT produce a complete staging baseline. It excludes auth/storage schemas, including the app's trigger
# on auth.users and storage policies; it omits grants; and a current live snapshot
# must not be blindly replayed before historical migrations. Do not run or apply
# its output without a reviewed schema/history and managed-service restore plan.
# Capture the live database into a baseline migration.
#
#   SUPABASE_DB_URL="postgresql://postgres:[pw]@db.<ref>.supabase.co:5432/postgres" \
#     ./scripts/capture-live-schema.sh
#
# Writes supabase/migrations/00000000000000_live_baseline.sql (schema only, no data,
# no owners, no grants for internal schemas). Run it once, review the diff, commit.
# The file is ordered before every existing migration so a fresh database replays
# baseline -> hardening -> Phase 1 in that order.
#
# A pg_dump client must be at least as new as the PostgreSQL server major version
# (17 for the inspected project). The script is UNVERIFIED in this sandbox.

set -euo pipefail

: "${SUPABASE_DB_URL:?set SUPABASE_DB_URL to the project's direct Postgres connection string}"

out="supabase/migrations/00000000000000_live_baseline.sql"
tmp="$(mktemp)"

if ! command -v pg_dump >/dev/null; then
  echo "pg_dump not found. Install postgresql-client-16+." >&2
  exit 1
fi

echo "==> dumping schema"
pg_dump "$SUPABASE_DB_URL" \
  --schema-only --no-owner --no-privileges --no-comments \
  --schema=public --schema=phase1_private \
  --exclude-schema=extensions --exclude-schema=graphql --exclude-schema=realtime \
  --exclude-schema=storage --exclude-schema=vault --exclude-schema=cron \
  > "$tmp"

{
  echo "-- Live baseline captured $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "-- Generated by scripts/capture-live-schema.sh. Schema only; contains no rows."
  echo "-- Rollback: delete this file (it is the first migration and has no dependants)."
  echo
  cat "$tmp"
} > "$out"

rm -f "$tmp"
echo "==> wrote $out ($(wc -l < "$out") lines)"

# Storage objects/RLS live in the storage schema and are managed by the dashboard,
# not by this dump. Bucket flags and object policies are asserted instead:
cat <<'SQL'

-- Expected after replay (verify manually, both are dashboard-owned):
--   storage.buckets: id-cards public=false, file_size_limit=3145728
--   storage.objects policies: entry_proof_read / entry_proof_insert /
--     entry_proof_delete / entry_proof_update / approvers read id cards /
--     approvers delete id cards / read own id card / upload own id card /
--     replace own id card / workspace_storage_gate / elevated_proof_read /
--     elevated_workspace_files
SELECT id, public, file_size_limit FROM storage.buckets WHERE id = 'id-cards';
SELECT policyname FROM pg_policies WHERE schemaname='storage' AND tablename='objects' ORDER BY 1;
SQL
